/*Идентификаторы в Go
Идентификатор в Go — это имя, которое программист использует для обозначения переменных, констант, функций, типов, пакетов и других сущностей программы. Правильное использование идентификаторов помогает сделать код понятным и поддерживаемым.

1. Допустимые идентификаторы в Go

Идентификатор — это последовательность символов, которая должна соответствовать определённым правилам. 

Правила для идентификаторов:
1. Идентификатор должен начинаться с буквы (`A-Z` или `a-z`) или символа подчёркивания (`_`).
2. За первым символом могут следовать буквы, цифры (`0-9`) или символ подчёркивания.
3. Идентификаторы чувствительны к регистру:
   - varName и VarName — разные идентификаторы.
4. Идентификатор не может быть таким же, как зарезервированное ключевое слово Go (например, func, var, `package`).

Примеры допустимых идентификаторов:
- x, counter, _value, MyVar123

Примеры недопустимых идентификаторов:
- 123abc (начинается с цифры)
- @var (содержит недопустимый символ)
- func (ключевое слово)

2. Блоки кода

Блок кода — это часть программы, заключённая в фигурные скобки {}. Блок кода определяет область действия идентификаторов.

Пример блока кода:
func main() {
    {
        x := 10 // Идентификатор x существует только внутри этого блока
        fmt.Println(x)
    }
    // fmt.Println(x) // Ошибка: x не определён в этой области видимости
}

Типы блоков кода:
1. Функциональные: Тело функции.
2. Условные: Внутри операторов if, for, switch.
3. Локальные: Блоки, определённые вручную с помощью фигурных скобок.

3. Области видимости

Область видимости определяет, где идентификатор доступен для использования.

Типы областей видимости:

1. Пакетная область видимости
- Идентификаторы, объявленные на уровне пакета (вне функций), доступны во всех файлах этого пакета.
- Пример:
   package main

  var globalVar = "visible in the package"

  func main() {
      fmt.Println(globalVar) // Доступен здесь
  }
  
2. Локальная область видимости
- Идентификаторы, объявленные внутри функции или блока, доступны только в пределах этого блока.
- Пример:
   func main() {
      x := 10 // Локальная переменная
      if true {
          y := 20 // Локальная переменная для блока if
          fmt.Println(x, y)
      }
      // fmt.Println(y) // Ошибка: y вне области видимости
  }
  
3. Область видимости пакетов (экспорт):
- Имена, начинающиеся с заглавной буквы, экспортируются из пакета и доступны в других пакетах.
- Пример:
   package mypackage

  var localVar = "not exported"    // Доступно только в пакете mypackage
  var ExportedVar = "exported"     // Доступно из других пакетов

4. Импорт/экспорт имён

Импорт пакетов
Для использования идентификаторов из других пакетов нужно импортировать их с помощью инструкции import.

Пример:
package main

import (
    "fmt"
)

func main() {
    fmt.Println("Hello, World!") // Имя Println экспортировано из пакета fmt
}

Экспорт имён
- Идентификатор экспортируется, если он начинается с заглавной буквы.
- Экспортированные имена доступны в других пакетах, если пакет импортирован.

Пример экспортированных имён:
package shapes

type Circle struct { // Экспортированный тип
    Radius float64
}

func NewCircle(radius float64) Circle { // Экспортированная функция
    return Circle{Radius: radius}
}

Использование в другом пакете:
package main

import (
    "shapes"
)

func main() {
    c := shapes.NewCircle(10)
    fmt.Println(c.Radius)
}

5. Связывание идентификатора с программной сущностью (binding)

Связывание (binding) — это процесс сопоставления имени идентификатора с определённой сущностью в программе, например, переменной, функцией или типом.

Пример связывания:
1. Связывание переменной:
     x := 10 // x связано с областью видимости функции main
   
2. Связывание функции:
     func add(a, b int) int {
       return a + b
   }
   
3. Связывание типов:
     type MyInt int // MyInt связано с типом int
   
Локальное и глобальное связывание:
- Если в функции объявляется идентификатор с таким же именем, как у глобального, локальный идентификатор «скрывает» глобальный.
- Пример:
   var x = 100 // Глобальный x

  func main() {
      x := 10 // Локальный x, глобальный x скрыт
      fmt.Println(x) // 10
  }
  
Итоги
Допустимые идентификаторы - Имена, начинающиеся с буквы или подчёркивания, чувствительные к регистру, не совпадают с ключевыми словами. 
Блоки кода - Области, определённые фигурными скобками, в которых действуют идентификаторы.                         
Области видимости - Уровни доступа к идентификаторам: локальная, пакетная, глобальная.                                   
Импорт/экспорт - Имена с заглавной буквы экспортируются и доступны в других пакетах.                                  
Связывание - Процесс привязки имени идентификатора к сущности (переменной, функции, типу).                        
*/
