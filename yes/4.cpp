/*Указатели в С++
 1. Что такое указатель?
Указатель — это переменная, которая хранит адрес другой переменной в памяти. Вместо значения указатель содержит номер ячейки памяти, где хранится другая переменная.

Пример:
int x = 10;      // Переменная x хранит значение 10
int* ptr = &x;   // Указатель ptr хранит адрес переменной x

Здесь:
- x — обычная переменная.
- &x — адрес переменной x.
- ptr — указатель, содержащий адрес переменной x.

 2. Объявление указателя
Указатель объявляется с указанием типа данных переменной, на которую он указывает, и символом *.

Синтаксис:
тип_данных* имя_указателя;

Пример:
int* p;      // Указатель на переменную типа int
double* q;   // Указатель на переменную типа double

Важно:
- Указатель и переменная должны иметь совместимые типы.
- Например, int* может хранить адрес только переменной типа int.

 3. Указатели и константность

Указатели могут быть связаны с константными данными или быть сами константами. Это определяет, можно ли изменять данные или сам указатель.

- Указатель на константу: нельзя изменить значение, на которое указывает указатель.
   const int x = 10;
  const int* ptr = &x; // ptr указывает на x, значение x менять нельзя
  
- Константный указатель: нельзя изменить адрес, хранящийся в указателе.
   int x = 10;
  int* const ptr = &x; // ptr всегда указывает на x, но значение x менять можно
  
- Константный указатель на константу: нельзя изменять ни адрес, ни значение.
   const int x = 10;
  const int* const ptr = &x;
  
4. Инициализация указателей

Инициализация указателя происходит путём присвоения ему адреса существующей переменной.

Пример:
int x = 42;
int* ptr = &x; // Указатель ptr хранит адрес переменной x

- Если указатель не инициализирован, его значение неопределено, что может привести к ошибкам.
- Для безопасной инициализации используют значение nullptr (вместо `NULL`):
   int* ptr = nullptr; // Указатель не указывает ни на что
  
5. Способы получения адреса

Адрес переменной можно получить с помощью оператора &.

Пример:
int x = 10;
int* ptr = &x; // ptr получает адрес переменной x

Способы получения адреса:
1. Операция `&`:
     int x = 42;
   int* ptr = &x; // ptr хранит адрес x
   2. Для массивов: имя массива уже является указателем на первый элемент:
     int arr[5] = {1, 2, 3, 4, 5};
   int* ptr = arr; // ptr указывает на первый элемент массива

 6. Виды указателей

Сырые указатели (raw pointers)
- Обычные указатели, работа с которыми требует ручного управления памятью.
- Пример:
   int* ptr = new int(10); // Динамическая память
  delete ptr;             // Освобождение памяти
  
 Типизированные указатели
- Указатели, привязанные к конкретному типу данных (`int*`, `char*`).
- Позволяют избежать ошибок, связанных с некорректным доступом.

 7. Преобразование типа указателя

Преобразование типов указателей осуществляется с помощью явного приведения.

Пример:
int x = 42;
void* ptr = &x;            // void* — универсальный указатель
int* intPtr = (int*)ptr;   // Приведение обратно к int*

Предпочтительный способ:
int* intPtr = static_cast<int*>(ptr);

 8. Логические операции с указателями

С указателями можно выполнять логические операции, такие как проверка на nullptr.

Пример:
if (ptr == nullptr) {
    cout << "Указатель пуст" << endl;
} else {
    cout << "Указатель не пуст" << endl;
}

 9. Арифметика указателей

Указатели поддерживают арифметические операции, такие как сложение и вычитание.

Пример:
int arr[3] = {10, 20, 30};
int* ptr = arr;

cout << *ptr << endl;  // Вывод: 10
ptr++;                 // Переход к следующему элементу
cout << *ptr << endl;  // Вывод: 20

Особенности:
- При добавлении/вычитании значение указателя сдвигается на размер типа данных.
- Например, если ptr — указатель на int (4 байта), ptr++ сдвигает указатель на 4 байта вперёд.

 10. Доступ к памяти, на которую указывает переменная-указатель

Для доступа к значению, хранящемуся по адресу, используется оператор разыменования (`*`).

int* ptr = &x;
cout << *ptr << endl; // Вывод: 42

 11. Связь указателя с массивами

Имя массива является указателем на его первый элемент.

Пример:
int arr[3] = {10, 20, 30};
int* ptr = arr;

cout << *ptr << endl;    // Вывод: 10 (первый элемент массива)
cout << *(ptr + 1) << endl; // Вывод: 20 (второй элемент)

 12. Размер указателя

Размер указателя зависит от архитектуры системы:
- 4 байта на 32-битной системе.
- 8 байт на 64-битной системе.

Итоги:

1. Указатель — переменная, хранящая адрес другой переменной.
2. Объявление указателя требует указания типа данных.
3. Указатели могут быть константными или указывать на константу.
4. Указатели инициализируются адресами переменных или nullptr.
5. Адрес переменной получают с помощью &.
6. Указатели бывают сырыми и типизированными.
7. Преобразование типов выполняется через явное приведение.
8. С указателями можно выполнять логические операции.
9. Арифметика указателей позволяет сдвигаться по памяти.
10. Для доступа к памяти используется разыменование (`*`).
11. Указатели тесно связаны с массивами.
12. Размер указателя фиксирован для конкретной архитектуры.
*/