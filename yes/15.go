/*Типы данных в языке Go
Golang (Go) — это язык с сильной и статической типизацией. Типы данных играют ключевую роль, так как каждый объект программы имеет определённый тип, который определяет его поведение и допустимые операции. Рассмотрим подробно основные аспекты.

1. Типизация

Виды типизации в Go:
1. Сильная типизация:
   - Go не допускает неявного преобразования между различными типами. Например, число int нельзя использовать там, где требуется float64, без явного преобразования.
   - Пример ошибки:
         var a int = 10
     var b float64 = a // Ошибка: нельзя неявно преобразовать int в float64
     
2. Статическая типизация:
   - Тип переменной определяется на этапе компиляции и не может быть изменён в процессе выполнения.
   - Пример:
         var a int = 10
     a = "hello" // Ошибка: переменной типа int нельзя присвоить значение типа string
     
3. Неявная типизация:
   - При использовании краткой формы объявления (`:=`) тип переменной определяется автоматически на основе значения:
         age := 25 // Go автоматически присвоит тип int


2. Простые типы данных

Go предоставляет несколько базовых (простых) типов данных, которые можно разделить на категории.

Числовые типы
1. Целые числа:
   - Типы:
     - int (размер зависит от платформы).
     - int8, int16, int32, int64 (целые числа заданной разрядности).
   - Беззнаковые типы:
     - uint (размер зависит от платформы).
     - uint8, uint16, uint32, uint64.
   - Пример:
         var x int = 42
     var y uint16 = 65535
     
2. Числа с плавающей точкой:
   - Типы:
     - float32 (32-битная точность).
     - float64 (64-битная точность, предпочтительный тип).
   - Пример:
         var pi float64 = 3.14159
     
3. Комплексные числа:
   - Типы:
     - complex64 (реальная и мнимая части типа `float32`).
     - complex128 (реальная и мнимая части типа `float64`).
   - Пример:
         var c complex128 = complex(3, 4) // 3 + 4i

Строки
- Строки (`string`) представляют собой последовательность байтов (символов в кодировке UTF-8).
- Пример:
   var message string = "Hello, Go!"

Булевы значения
- Тип bool имеет только два значения: true или false.
- Пример:
   var isReady bool = true

3. Составные типы данных

Составные типы позволяют группировать данные.

Слайсы (Slices)
- Динамический массив.
- Пример:
   var nums []int = []int{1, 2, 3, 4}
  
Массивы (Arrays)
- Фиксированный размер.
- Пример:
   var arr [3]int = [3]int{1, 2, 3}
  
Словари (Maps)
- Ассоциативный массив (ключ-значение).
- Пример:
   var dict map[string]int = map[string]int{"a": 1, "b": 2}
  
Структуры (Structs)
- Пользовательский тип данных для объединения полей разных типов.
- Пример:
   type Person struct {
      Name string
      Age  int
  }
  
Интерфейсы (Interfaces)
- Определяют набор методов, которые должен реализовать тип.
- Пример:
   type Shape interface {
      Area() float64
  }

 4. Объявление типа

Go позволяет создавать собственные типы на основе существующих.

Пример:
type Age int
type Temperature float64

- После объявления Age и Temperature считаются отдельными типами, и операции между ними и их базовыми типами невозможны без преобразования.

---

5. Псевдоним типа

Псевдонимы создаются с помощью ключевого слова type и используются для создания новых имён для существующих типов.

Пример:
type ID = string
- Здесь ID — это псевдоним типа string. По сути, они эквивалентны.

6. Преобразование типов

Преобразование типов в Go бывает явным и неявным.

1. Явное преобразование:
- Выполняется вручную с помощью синтаксиса Type(value).
- Пример:
   var x int = 42
  var y float64 = float64(x) // Преобразование int в float64
  
2. Неявное преобразование:
- Go не поддерживает автоматическое преобразование между типами. Это сделано для предотвращения ошибок.

Пример явного преобразования:
package main

import "fmt"

func main() {
    var a int = 10
    var b float64 = 3.5

    // Явное преобразование
    c := float64(a) + b
    fmt.Println("Result:", c)
}

Итог
Простые типы - int, float64, string, bool  - Основные типы данных для чисел, строк, булевых значений.                   
Составные типы - []int, map[string]int, struct  - Для группировки данных и сложных структур.                                 
Псевдонимы  - type ID = string - Новый идентификатор для существующего типа.                                
Пользовательские - type Age int - Создание полностью нового типа на основе существующего.                   
Преобразование - float64(intValue) - Только явное преобразование между несовместимыми типами.                  
*/
