/*Переменные и константы в С++

1. Создание переменных и констант
 Что такое переменные?
Переменная — это именованная область памяти, в которой хранится значение, изменяемое в ходе работы программы.
 Что такое константы?
Константа — это именованная область памяти, значение которой остаётся неизменным на протяжении работы программы.

Создание переменных
В C++ переменная создаётся с указанием типа данных. 
Общие правила создания:
1. Указывается тип данных (`int`, float, char, и т.д.).
2. Указывается имя переменной.
3. При необходимости — начальное значение.
 Создание констант

Для объявления константы используется ключевое слово const или макросы через #define.

Пример с `const`:
const int MAX_SCORE = 100; // Константа, значение не изменится

Пример с `#define`:
#define PI 3.14 // Макрос-константа

Отличие `const` и `#define`:
- const работает как переменная и имеет тип данных.
- #define обрабатывается на этапе препроцессирования и не имеет типа данных.

2. Использование переменных и констант
 Переменные
Переменные можно читать и изменять.
Типичные операции с переменными:
- Присваивание: x = 10;
- Арифметические операции: x + y, x * y.
- Условные операции: if (x > y).
- Ввод/вывод: cin, cout.

 Константы
Константы используются для значений, которые не должны изменяться.
Почему использовать константы:
- Защита от случайного изменения.
- Улучшение читаемости кода (например, вместо числа 3.14159 используем `PI`).

 3. Уничтожение переменных и констант
 Уничтожение переменных

- Локальные переменные: 
  Переменные, созданные внутри функции, уничтожаются автоматически при выходе из функции. Память, выделенная для переменной, освобождается.
- Глобальные переменные:
  Уничтожаются автоматически при завершении программы.
 -Динамические переменные:
Если память выделяется динамически (через new`), её необходимо освобождать вручную с помощью `delete.

 Уничтожение констант
- Константы, созданные с помощью const, подчиняются тем же правилам, что и переменные: локальные уничтожаются при выходе из области видимости, глобальные — при завершении программы.
- Константы, созданные с помощью #define, не занимают памяти и обрабатываются на этапе препроцессирования.
 Итог:
1. Создание:
   - Переменные объявляются с указанием типа, имя и, возможно, начального значения.
   - Константы объявляются через const или #define.
2. Использование:
   - Переменные можно изменять, выполнять с ними операции.
   - Константы используются для неизменяемых данных.
3. Уничтожение:
   - Локальные переменные уничтожаются при выходе из функции.
   - Глобальные переменные и константы — при завершении программы.
   - Динамические переменные нужно освобождать вручную.
*/