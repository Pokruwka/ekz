/*Поток исполнения программы на Go
Поток исполнения программы в Go — это последовательность инструкций, которые выполняются процессором. В Go программный поток организуется через функции, операторы, выражения и стейтменты. Рассмотрим основные аспекты.

1. Точка входа в программу

В языке Go точкой входа в программу является функция main, которая определяется в пакете main. Без функции main программа не будет скомпилирована.

Правила:
1. Функция main обязана находиться в пакете с именем main.
2. Функция main не принимает аргументов и не возвращает значения.
3. Выполнение программы начинается с вызова main и завершается, когда функция main завершает своё выполнение.

Пример:
package main

import "fmt"

// Точка входа
func main() {
    fmt.Println("Hello, Go!") // Вывод текста в консоль
}

---

2. Операторы

Операторы в Go используются для выполнения различных операций над данными, таких как арифметические вычисления, сравнения, логические проверки и другие.

Виды операторов

1. Арифметические операторы:
   - + (сложение), - (вычитание), * (умножение), / (деление), % (остаток от деления).
   - Пример:
         a, b := 10, 3
     fmt.Println(a + b) // 13
     fmt.Println(a % b) // 1
     
2. Операторы сравнения:
   - ==, !=, <, >, <=, >=.
   - Пример:
         fmt.Println(5 > 3) // true
     
3. Логические операторы:
   - && (И), || (ИЛИ), ! (НЕ).
   - Пример:
         fmt.Println(true && false) // false
     
4. Операторы присваивания:
   - =, +=, -=, *=, /=, %=.
   - Пример:
         x := 5
     x += 2
     fmt.Println(x) // 7
     
5. Операторы указателей:
   - & (адрес переменной), * (разыменование указателя).
   - Пример:
         x := 10
     p := &x
     fmt.Println(*p) // 10

Приоритет операторов

Приоритет определяет порядок выполнения операций. Например, умножение и деление выполняются перед сложением и вычитанием.

Таблица приоритетов (от высокого к низкому):
1. Арифметические операции: *, /, %
2. Сложение и вычитание: +, -
3. Операторы сравнения: <, <=, >, >=
4. Операторы равенства: ==, !=
5. Логические операторы: &&, ||

Пример:
result := 5 + 2 * 3 // 5 + (2 * 3) = 11

3. Выражение

Что такое выражение?
Выражение — это комбинация переменных, констант, операторов и функций, которая вычисляется и возвращает значение.

Пример выражения:
a, b := 10, 20
result := a + b * 2 // Выражение возвращает результат: 50

Порядок вычислений в выражении
1. Слева направо с учётом приоритета операторов.
2. Если приоритет операторов одинаковый, вычисления происходят в порядке их появления.

4. Стейтмент

Что такое стейтмент?
Стейтмент (statement) — это инструкция, которая выполняет действие. В отличие от выражения, стейтмент может не возвращать значение.

Основные виды стейтментов:
1. Присваивание:
     x := 10
   2. Условный оператор:
     if x > 5 {
       fmt.Println("x больше 5")
   }
   3. Циклы:
     for i := 0; i < 5; i++ {
       fmt.Println(i)
   }
   4. Оператор выбора (`switch`):
     switch day := "Monday"; day {
   case "Monday":
       fmt.Println("Начало недели")
   default:
       fmt.Println("Другой день")
   }
   
Отличие стейтмента от выражения:
- Выражение возвращает значение:
   result := a + b
  - Стейтмент выполняет действие:
   x := 10
  if x > 5 {
      fmt.Println("Большое число")
  }

5. Функция

### Функция и поток выполнения
Функция — это логический блок кода, который выполняет определённую задачу. Она может вызываться в разных местах программы, влияя на поток выполнения.

Влияние функции на поток исполнения:
1. При вызове функции выполнение программы передаётся этой функции.
2. После завершения выполнения функции управление возвращается в точку её вызова.

Пример:
package main

import "fmt"

func greet(name string) {
    fmt.Println("Hello,", name)
}

func main() {
    greet("Alice")
    fmt.Println("Program ended")
}

- Поток выполнения:
  1. Выполнение начинается с main.
  2. Вызов greet передаёт управление в функцию.
  3. После завершения greet выполнение возвращается в main.

Особенности функций:
1. Аргументы:
   - Функции могут принимать входные значения.
     func add(a int, b int) int {
       return a + b
   }
   
2. Возвращаемое значение:
   - Функции могут возвращать одно или несколько значений.
     func divide(a, b int) (int, int) {
       return a / b, a % b
   }
   
3. Анонимные функции:
   - Функции без имени можно использовать для краткосрочных операций.
     func main() {
       func() {
           fmt.Println("Anonymous function")
       }()
   }

Итоги
Точка входа - Функция main в пакете main — начало выполнения программы.                              
Операторы  - Инструменты для выполнения действий над данными (арифметика, сравнение, логика).            
Выражения - Комбинации данных и операторов, возвращающие значение.                                     
Стейтменты - Инструкции, выполняющие действия (присваивания, циклы, условия).                           
Функции - Логические блоки, управляющие выполнением программы и обеспечивающие повторное использование кода. 
*/
