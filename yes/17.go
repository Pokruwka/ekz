/*Функции в языке Go
Функции в Go — это основная конструкция для организации кода и повторного использования логики. Они представляют собой блок кода с определённой задачей, который может быть вызван из других частей программы.

1. Объявление функции

Правила объявления функции
1. Функция объявляется с использованием ключевого слова func.
2. После ключевого слова func указывается имя функции.
3. Далее идут круглые скобки, в которых можно указать параметры.
4. После параметров указывается возвращаемый тип (если функция возвращает значение).
5. Тело функции заключается в фигурные скобки {}.

Синтаксис:
func имяФункции(параметры) возвращаемые_типы {
    // Тело функции
}

Параметры функции
Параметры функции передаются через скобки при объявлении. Каждый параметр должен иметь имя и тип.

Примеры:
1. Одна пара параметров:
     func greet(name string) {
       fmt.Println("Hello,", name)
   }
      Здесь параметр name имеет тип string.

2. Несколько параметров:
     func add(a int, b int) int {
       return a + b
   }
      Параметры a и b имеют тип int.

3. Параметры одного типа можно группировать:
     func multiply(a, b, c int) int {
       return a * b * c
   }

Аргументы функции
- Аргументы передаются функции при её вызове.
- Тип аргумента должен совпадать с типом параметра.

Пример:
func greet(name string) {
    fmt.Println("Hello,", name)
}

func main() {
    greet("Alice") // Аргумент "Alice" передаётся параметру name
}

Возврат значений
Функция может возвращать одно или несколько значений. Для этого после параметров указывается возвращаемый тип.

Примеры:
1. Функция возвращает одно значение:
     func square(x int) int {
       return x * x
   }
   
2. Функция возвращает несколько значений:
     func divide(a, b int) (int, int) {
       return a / b, a % b
   }
   
3. Именованные возвращаемые значения:
   - Возвращаемые значения можно именовать и использовать внутри функции как переменные.
     func stats(a, b int) (sum, product int) {
       sum = a + b
       product = a * b
       return // Именованные переменные возвращаются автоматически
   }
   
4. Функция без возвращаемого значения:
     func printMessage() {
       fmt.Println("This is a message.")
   }
   
---

2. Использование функции

Вызов функции
Для вызова функции используется её имя с указанием аргументов в скобках. 

Пример:
func add(a, b int) int {
    return a + b
}

func main() {
    result := add(3, 4) // Вызов функции с аргументами 3 и 4
    fmt.Println(result) // 7
}

---

Стек вызовов
- Каждый вызов функции создаёт новый фрейм (кадр) в стеке вызовов.
- Фрейм содержит информацию о локальных переменных, аргументах и возвращаемых значениях.
- После завершения функции её фрейм удаляется из стека, и выполнение продолжается с точки вызова.

Пример:
func main() {
    fmt.Println("Start")
    first()
    fmt.Println("End")
}

func first() {
    second()
}

func second() {
    fmt.Println("Inside second function")
}

Результат выполнения:
Start
Inside second function
End

Возврат из функции
- Возврат значения осуществляется через ключевое слово return.
- Если функция возвращает несколько значений, они указываются через запятую.

Пример:
func calculate(a, b int) (int, int) {
    sum := a + b
    diff := a - b
    return sum, diff
}

func main() {
    result1, result2 := calculate(5, 3)
    fmt.Println(result1, result2) // 8 2
}

3. Функция `main`

Особенности функции `main`:
1. main — это точка входа в программу.
2. Находится в пакете main.
3. Не принимает аргументов и не возвращает значений.
4. Именно с этой функции начинается выполнение программы.

Пример:
package main

import "fmt"

func main() {
    fmt.Println("Hello, Go!") // Выполнение программы начинается здесь
}

Связь с остальными функциями
- Функция main вызывает другие функции, если это необходимо.
- Все вспомогательные функции определяются отдельно и вызываются из main.

Пример программы:
package main

import "fmt"

func add(a, b int) int {
    return a + b
}

func main() {
    sum := add(10, 20) // Вызов функции add
    fmt.Println("Sum is:", sum)
}

Итоги
Объявление функции - Используется ключевое слово func. Функция может принимать параметры и возвращать значения.          
Параметры  - Передаются в скобках при объявлении, должны быть указаны имя и тип.                                  
Возврат значений - Указывается после параметров, может быть несколько возвращаемых значений.                            
Использование  - Вызов функции осуществляется по имени с передачей аргументов.                                       
Стек вызовов - Каждая функция добавляется в стек, и управление возвращается в точку вызова после её завершения.     
Функция `main` - Точка входа программы. Выполняет начальную инициализацию и вызывает другие функции.                  
*/
